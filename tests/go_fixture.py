"""Synthetic, deterministic GO-report fixture (no randomness, no database).

Builds ``SetData`` for two sets (``all`` with two runs, ``excl_conditional``) over ~41 days and
renders the committed sample ``docs/quant/samples/go-report-sample.md``::

    uv run python -m tests.go_fixture
"""

from __future__ import annotations

from collections.abc import Callable
from datetime import UTC, datetime
from decimal import Decimal as D
from pathlib import Path

from nexus.reports.go_build import FeeObservation, build_report
from nexus.reports.go_math import (
    DAY_MS,
    HOUR_MS,
    CapHour,
    HoldingPoint,
    RebalanceRecord,
    RunInfo,
    SetData,
    SkipRecord,
    SnapshotSet,
    TradeRecord,
)
from nexus.reports.go_render import render_markdown
from nexus.reports.go_verdict import GateStatus, OpsInputs

SAMPLE_PATH = Path("docs/quant/samples/go-report-sample.md")
BANNER = (
    "> SYNTHETIC SAMPLE (AC 6): generated by `uv run python -m tests.go_fixture` from a "
    "deterministic fixture. The numbers are invented; only the structure is real.\n\n"
)


def ms(year: int, month: int, day: int, hour: int = 0, minute: int = 0) -> int:
    """UTC instant in epoch milliseconds."""
    return int(datetime(year, month, day, hour, minute, tzinfo=UTC).timestamp() * 1000)


UNTIL = ms(2026, 12, 5)
# (symbol, base, buy, sell, average net USD per trade per day)
SAFE_ROUTES = [
    ("ABC/USDT", "ABC", "binance", "kucoin", D("2.2")),
    ("DEF/USDT", "DEF", "binance", "okx", D("2.1")),
    ("GHI/USDT", "GHI", "kucoin", "okx", D("2.0")),
    ("JKL/USDT", "JKL", "okx", "kucoin", D("2.0")),
    ("MNO/USDT", "MNO", "binance", "okx", D("2.0")),
    ("PQR/USDT", "PQR", "kucoin", "binance", D("2.0")),
    ("STU/USDT", "STU", "okx", "binance", D("1.9")),
    ("VWX/USDT", "VWX", "binance", "kucoin", D("1.9")),
]
BYBIT_ROUTE = ("ABC/USDT", "ABC", "bybit", "kucoin", D("9.0"))  # makes `all` concentrated
COINS = {"ABC": D(1), "DEF": D(2), "GHI": D(1), "JKL": D(1)}


def _price(coin: str, day: int) -> D:
    wave = D((day * 7 + len(coin) * 3) % 11 - 5) / D(200)
    return COINS[coin] * (1 + wave)


def make_set(
    name: str,
    venues: tuple[str, ...],
    start_ms: int,
    routes: list[tuple[str, str, str, str, D]],
    *,
    run_id: int,
    previous: tuple[RunInfo, ...] = (),
    gap_day: int | None = None,
    factor: Callable[[int], D] | None = None,
    until_ms: int = UNTIL,
) -> SetData:
    """One set: a trade per route per day, daily snapshots, hourly sweeps, a few transfers."""
    capital = D(10_000)
    run = RunInfo(run_id, start_ms, tuple(sorted(venues)), capital, f"{name:_<8}{run_id:0>56}")
    n_days = (until_ms - start_ms) // DAY_MS + 1
    trades: list[TradeRecord] = []
    skips: list[SkipRecord] = []
    rebals: list[RebalanceRecord] = []
    snapshots: list[SnapshotSet] = []
    caps: list[CapHour] = []
    cash = D(0)
    for d in range(n_days):
        day = start_ms + d * DAY_MS
        mult = factor(d) if factor else D(8 + (d * 5) % 7) / D(11)  # 0.73 .. 1.27
        for i, (symbol, base, buy, sell, avg) in enumerate(routes):
            at = day + (6 + i) * HOUR_MS
            net = (avg * mult).quantize(D("0.0001"))
            trades.append(TradeRecord(at, symbol, base, buy, sell, net, D(250)))
            cash += net
        for k, reason in enumerate(("spread_gone", "insufficient_coin", "recent_fill")):
            skips.append(SkipRecord(day + (14 + k) * HOUR_MS, reason))
        if d % 17 == 5:
            skips.append(SkipRecord(day + 18 * HOUR_MS, "coin_budget_exhausted"))
        if d % 5 == 2:
            fee = D("1.2")
            rebals.append(
                RebalanceRecord(day + 9 * HOUR_MS, day + 10 * HOUR_MS, "USDT", "kucoin",
                                "binance", D(400), D(1), fee, "TRC20", "completed")
            )  # fmt: skip
            cash -= fee
        if d % 9 == 4:
            fee = D("0.8")
            rebals.append(
                RebalanceRecord(day + 11 * HOUR_MS, day + 12 * HOUR_MS, "ABC", "binance",
                                "kucoin", D(40), D("0.8"), fee, "BEP20", "completed")
            )  # fmt: skip
            cash -= fee
        if d == 20:
            fee = D("0.7")
            rebals.append(
                RebalanceRecord(day + 13 * HOUR_MS, day + 13 * HOUR_MS, "GHI", "okx", "okx",
                                D(100), D("0.7"), fee, "conversion", "completed")
            )  # fmt: skip
            cash -= fee
        holdings = [
            HoldingPoint("binance", "USDT", D(1250) + cash, D(1), D(1250)),
            HoldingPoint("kucoin", "USDT", D(1250), D(1), D(1250)),
            HoldingPoint("okx", "USDT", D(1250), D(1), D(1250)),
        ]
        for venue in ("kucoin", "okx"):
            for coin in ("ABC", "DEF"):
                seed_price = COINS[coin]
                amount = D(250) / seed_price
                holdings.append(
                    HoldingPoint(venue, coin, amount, _price(coin, d), amount * seed_price)
                )
        holdings.append(HoldingPoint("binance", "JKL", D("40"), _price("JKL", d), D(0)))
        snapshots.append(SnapshotSet(day + 23 * HOUR_MS, tuple(holdings)))
        for h in range(24):
            if gap_day == d and 3 <= h < 6:
                continue  # a scanner outage: three hours without a sweep
            bound = 40 if d % 6 == 0 else 4
            caps.append(
                CapHour(
                    day // HOUR_MS * HOUR_MS + h * HOUR_MS,
                    120,
                    bound,
                    bound * 3,
                    1 if bound > 4 else 0,
                )
            )
    return SetData(
        name=name,
        run=run,
        previous_runs=previous,
        snapshots=tuple(s for s in snapshots if s.at_ms < until_ms),
        trades=tuple(t for t in trades if t.at_ms < until_ms),
        skips=tuple(s for s in skips if s.at_ms < until_ms),
        rebalances=tuple(r for r in rebals if r.started_ms < until_ms),
        caps=tuple(c for c in caps if c.hour_ms < until_ms),
    )


def fixture_sets() -> list[SetData]:
    """``all`` (second run, Bybit route inside) and ``excl_conditional``."""
    first_all = RunInfo(1, ms(2026, 10, 24, 14, 5), ("binance", "bybit"), D(10_000), "legacy")
    return [
        make_set(
            "all",
            ("binance", "bybit", "gateio", "kucoin", "okx"),
            ms(2026, 10, 26, 9, 30),
            [BYBIT_ROUTE, *SAFE_ROUTES[:4]],
            run_id=3,
            previous=(first_all,),
            gap_day=12,
        ),
        make_set(
            "excl_conditional",
            ("binance", "kucoin", "okx"),
            ms(2026, 10, 24, 14, 5),
            SAFE_ROUTES,
            run_id=2,
        ),
    ]


def sample_markdown() -> str:
    """The committed sample: GO set `excl_conditional`, legal/access gates still open."""
    report = build_report(
        fixture_sets(),
        until_ms=UNTIL,
        go_set="excl_conditional",
        gates=GateStatus(open_gates=("G1.1", "G1.3", "G3.1", "DNI", "keys for all venues")),
        ops={
            "excl_conditional": OpsInputs(
                timed_out_pct=D("0.8"), membership_missing=0, regimes=("calm", "volatile", "calm")
            ),
            "all": OpsInputs(timed_out_pct=D("0.9"), membership_missing=0),
        },
        fees=[
            FeeObservation("binance", 480, D("0.1000"), D("0.0750"), D("0.1000")),
            FeeObservation("kucoin", 505, D("0.1000"), D("0.1000"), D("0.1000")),
            FeeObservation("okx", 497, D("0.0800"), D("0.0800"), D("0.1000")),
        ],
    )
    return BANNER + render_markdown(report)


if __name__ == "__main__":
    SAMPLE_PATH.write_text(sample_markdown(), encoding="utf-8")
